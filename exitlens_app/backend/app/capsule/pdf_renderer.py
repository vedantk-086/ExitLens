class NumberedCanvas(canvas.Canvas):
    """Canvas that adds running headers and page numbers on all pages."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Any] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#718096"))

        # Running header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, letter[1] - 36, "ExitLens — Dependency Exit Capsule")
            self.drawRightString(letter[0] - 54, letter[1] - 36, "Confidential — Migration Intelligence")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Running footer
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawString(54, 36, "Generated by ExitLens | Non-executing static AST & risk engine analysis")
        self.drawRightString(letter[0] - 54, 36, page_str)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 46, letter[0] - 54, 46)
        self.restoreState()


def build_capsule_pdf_bytes(capsule: DependencyExitCapsule) -> bytes:
    """Render a DependencyExitCapsule into a PDF binary buffer."""
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    brand_blue = colors.HexColor("#1A365D")
    accent_blue = colors.HexColor("#2B6CB0")
    dark_gray = colors.HexColor("#2D3748")
    light_bg = colors.HexColor("#F7FAFC")
    border_color = colors.HexColor("#E2E8F0")

    title_style = ParagraphStyle(
        "DocTitle",
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=26,
        textColor=brand_blue,
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "DocSub",
        fontName="Helvetica",
        fontSize=11,
        leading=15,
        textColor=accent_blue,
        spaceAfter=14,
    )
    h1_style = ParagraphStyle(
        "H1",
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=brand_blue,
        spaceBefore=12,
        spaceAfter=8,
        keepWithNext=True,
    )
    h2_style = ParagraphStyle(
        "H2",
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=accent_blue,
        spaceBefore=8,
        spaceAfter=4,
        keepWithNext=True,
    )
    body_style = ParagraphStyle(
        "Body",
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=dark_gray,
        spaceAfter=4,
    )
    bold_style = ParagraphStyle(
        "BodyBold",
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=dark_gray,
    )
    code_style = ParagraphStyle(
        "CodeText",
        fontName="Courier",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#805AD5"),
    )

    elements: List[Any] = []

    # Title & Header
    elements.append(Paragraph("ExitLens — Dependency Exit Capsule", title_style))
    elements.append(Paragraph("Autonomous Dependency Migration & Risk Intelligence Report", subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=brand_blue, spaceBefore=0, spaceAfter=12))

    # Metadata & Scope Block
    meta_data = [
        [
            Paragraph("<b>Target Repository:</b>", body_style),
            Paragraph(capsule.repository.source, code_style),
            Paragraph("<b>Analysis ID:</b>", body_style),
            Paragraph(capsule.analysis_id, code_style),
        ],
        [
            Paragraph("<b>Commit Revision:</b>", body_style),
            Paragraph(capsule.repository.revision or "HEAD", code_style),
            Paragraph("<b>Generated UTC:</b>", body_style),
            Paragraph(capsule.generated_at_utc[:19].replace("T", " "), body_style),
        ],
        [
            Paragraph("<b>Python Specification:</b>", body_style),
            Paragraph(f"Python {capsule.repository.python_version}", body_style),
            Paragraph("<b>AI Provider:</b>", body_style),
            Paragraph(f"{capsule.ai_provenance.provider} ({capsule.ai_provenance.model_id})", body_style),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[110, 150, 100, 144])
    meta_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), light_bg),
            ("BOX", (0, 0), (-1, -1), 0.5, border_color),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    elements.append(meta_table)
    elements.append(Spacer(1, 14))

    # Executive Summary Metrics
    elements.append(Paragraph("1. Executive Summary", h1_style))
    sum_data = [
        [
            Paragraph("<b>Total Dependencies Discovered</b>", body_style),
            Paragraph(str(capsule.summary.dependencies_discovered), bold_style),
            Paragraph("<b>Flagged for Migration</b>", body_style),
            Paragraph(str(capsule.summary.dependencies_flagged), bold_style),
        ],
        [
            Paragraph("<b>Migration Candidates Identified</b>", body_style),
            Paragraph(str(capsule.summary.recommendations_available), bold_style),
            Paragraph("<b>Scan Method</b>", body_style),
            Paragraph("Static AST (Non-executing)", body_style),
        ],
    ]
    sum_table = Table(sum_data, colWidths=[150, 100, 150, 104])
    sum_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EBF8FF")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#BEE3F8")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#BEE3F8")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ])
    )
    elements.append(sum_table)
    elements.append(Spacer(1, 14))

    # Flagged Dependencies Summary Table
    elements.append(Paragraph("2. Flagged Dependencies Overview", h1_style))
    dep_headers = [
        Paragraph("<b>Package</b>", bold_style),
        Paragraph("<b>Declared Specifier</b>", bold_style),
        Paragraph("<b>Manifest</b>", bold_style),
        Paragraph("<b>Usages</b>", bold_style),
        Paragraph("<b>Primary Risk Rule</b>", bold_style),
        Paragraph("<b>Proposed Candidate</b>", bold_style),
    ]
    dep_rows = [dep_headers]

    for d in capsule.dependencies:
        details = d.dependency_details
        risks = d.risk_indicators
        primary_risk = risks[0].rule_id if risks else "REVIEW"
        prop = d.proposed_replacement
        cand_str = prop.distribution_name or prop.status

        dep_rows.append([
            Paragraph(f"<b>{details.distribution_name}</b>", body_style),
            Paragraph(details.declared_specifier or "unpinned", code_style),
            Paragraph(details.manifest_path or "—", body_style),
            Paragraph(str(len(d.usage_locations)), body_style),
            Paragraph(primary_risk, body_style),
            Paragraph(cand_str, bold_style),
        ])

    dep_table = Table(dep_rows, colWidths=[80, 80, 95, 45, 104, 100])
    dep_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
            ("BOX", (0, 0), (-1, -1), 0.5, border_color),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, light_bg]),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    elements.append(dep_table)
    elements.append(Spacer(1, 16))

    section_title_style = ParagraphStyle(
        "SectionTitle",
        fontName="Helvetica-Bold",
        fontSize=9.5,
        leading=13,
        textColor=brand_blue,
        spaceBefore=6,
        spaceAfter=2,
        keepWithNext=True,
    )
    muted_style = ParagraphStyle(
        "Muted",
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#718096"),
        spaceAfter=3,
    )

    # Detailed Migration Plans for Flagged Dependencies
    elements.append(PageBreak())
    elements.append(Paragraph("3. Detailed Migration Analysis & Action Plans", h1_style))
    elements.append(Paragraph(
        "Each flagged dependency below contains observed static usages, deterministic risk indicators, "
        "and Google AI Studio Gemma 4 migration plans covering all 9 capsule sections.", body_style
    ))
    elements.append(Spacer(1, 8))

    for idx, d in enumerate(capsule.dependencies, 1):
        details = d.dependency_details
        prop = d.proposed_replacement

        dep_title = f"{idx}. Package: {details.distribution_name} ({details.declared_specifier or 'unpinned'})"
        elements.append(Paragraph(dep_title, h2_style))

        # 1. Dependency Details
        elements.append(Paragraph("<b>1. Dependency Details</b>", section_title_style))
        info_data = [
            [
                Paragraph("<b>Distribution Name:</b>", body_style),
                Paragraph(details.distribution_name, bold_style),
                Paragraph("<b>Manifest Path:</b>", body_style),
                Paragraph(details.manifest_path or "—", code_style),
            ],
            [
                Paragraph("<b>Declared Specifier:</b>", body_style),
                Paragraph(details.declared_specifier or "unpinned", code_style),
                Paragraph("<b>Resolved Version:</b>", body_style),
                Paragraph(details.resolved_version or "Unresolved / Drift", body_style),
            ],
            [
                Paragraph("<b>Package Manager:</b>", body_style),
                Paragraph(details.package_manager, body_style),
                Paragraph("<b>Classification:</b>", body_style),
                Paragraph(f"{details.dependency_type} (Markers: {details.runtime_markers or 'None'})", body_style),
            ],
        ]
        info_t = Table(info_data, colWidths=[110, 142, 100, 152])
        info_t.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), light_bg),
                ("BOX", (0, 0), (-1, -1), 0.5, border_color),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ])
        )
        elements.append(info_t)
        elements.append(Spacer(1, 3))

        # 2. Risk Indicators
        elements.append(Paragraph(f"<b>2. Risk Indicators ({len(d.risk_indicators)})</b>", section_title_style))
        if d.risk_indicators:
            risk_texts = [
                f"• <b>[{r.severity.upper()}] {r.rule_id}:</b> {r.title} — {r.explanation}"
                for r in d.risk_indicators
            ]
            elements.append(Paragraph("<br/>".join(risk_texts), body_style))
        else:
            elements.append(Paragraph("<i>No active risk indicators flagged.</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 3. Usage Locations
        elements.append(Paragraph(f"<b>3. Usage Locations ({len(d.usage_locations)} occurrences)</b>", section_title_style))
        if d.usage_locations:
            usage_texts = []
            for u in d.usage_locations[:6]:
                line_str = f"L{u.line_start}-{u.line_end}" if u.line_start else "Line N/A"
                sym = u.symbol or u.import_statement or "Import reference"
                usage_texts.append(f"• <code>{u.path}</code> ({line_str}): <code>{sym}</code> [ref: {u.evidence_id}]")
            if len(d.usage_locations) > 6:
                usage_texts.append(f"• <i>... and {len(d.usage_locations) - 6} additional usage locations.</i>")
            elements.append(Paragraph("<br/>".join(usage_texts), body_style))
        else:
            elements.append(Paragraph("<i>No static imports discovered in source files (may be dynamic or CLI entrypoint).</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 4. Proposed Replacement
        elements.append(Paragraph("<b>4. Proposed Replacement</b>", section_title_style))
        cand_str = f"<b>{prop.distribution_name}</b> {prop.specifier or ''}" if prop.distribution_name else "<i>None identified</i>"
        prop_texts = [
            f"• <b>Status:</b> {prop.status} | <b>Validation Status:</b> {prop.candidate_validation_status}",
            f"• <b>Candidate:</b> {cand_str}",
            f"• <b>Rationale:</b> {prop.rationale or 'None'}",
        ]
        elements.append(Paragraph("<br/>".join(prop_texts), body_style))
        elements.append(Spacer(1, 3))

        # 5. Migration Steps
        elements.append(Paragraph(f"<b>5. Migration Steps ({len(d.migration_steps)})</b>", section_title_style))
        if d.migration_steps:
            step_texts = []
            for s in d.migration_steps:
                target_info = f" [Target: {s.target_file}]" if s.target_file else ""
                step_texts.append(f"<b>{s.step_number}. {s.action}:</b> {s.description}{target_info}")
            elements.append(Paragraph("<br/>".join(step_texts), body_style))
        else:
            elements.append(Paragraph("<i>No concrete migration steps identified.</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 6. Suggested Tests
        elements.append(Paragraph(f"<b>6. Suggested Tests ({len(d.suggested_tests)})</b>", section_title_style))
        if d.suggested_tests:
            test_texts = [
                f"• <b>[{t.suggested_profile}]</b> {t.objective} (Expected signal: {t.expected_signal})"
                for t in d.suggested_tests
            ]
            elements.append(Paragraph("<br/>".join(test_texts), body_style))
        else:
            elements.append(Paragraph("<i>No custom tests suggested by model.</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 7. Executed Test Results
        elements.append(Paragraph("<b>7. Executed Test Results</b>", section_title_style))
        if d.executed_test_results:
            exec_texts = [
                f"• <b>[{res.status.value}]</b> Profile: {res.profile_id} (Exit code: {res.exit_code}, Duration: {res.duration_seconds}s) — {res.skip_or_error_reason or 'Completed'}"
                for res in d.executed_test_results
            ]
            elements.append(Paragraph("<br/>".join(exec_texts), body_style))
        else:
            elements.append(Paragraph("<i>None (Verification tests NOT_RUN / SKIPPED — repository code execution requires explicit human authorization).</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 8. Compatibility Gaps
        elements.append(Paragraph(f"<b>8. Compatibility Gaps ({len(d.compatibility_gaps)})</b>", section_title_style))
        if d.compatibility_gaps:
            gap_texts = [
                f"• <b>{g.title}</b> ({'Verified' if g.verified else 'Inferred'}): {g.description}"
                for g in d.compatibility_gaps
            ]
            elements.append(Paragraph("<br/>".join(gap_texts), body_style))
        else:
            elements.append(Paragraph("<i>None identified via static analysis (dynamic verification required).</i>", muted_style))
        elements.append(Spacer(1, 3))

        # 9. Open Concerns & Limitations
        elements.append(Paragraph(f"<b>9. Open Concerns & Limitations ({len(d.open_concerns_limitations)})</b>", section_title_style))
        if d.open_concerns_limitations:
            concern_texts = [f"• {c}" for c in d.open_concerns_limitations]
            elements.append(Paragraph("<br/>".join(concern_texts), body_style))
        else:
            elements.append(Paragraph("<i>Verification bounded by non-executing static analysis.</i>", muted_style))

        elements.append(HRFlowable(width="100%", thickness=0.8, color=border_color, spaceBefore=8, spaceAfter=14))

    # Safety & Non-Executing Attestation
    elements.append(Spacer(1, 10))
    elements.append(Paragraph("4. Safety & Verification Attestation", h1_style))
    attestation_text = (
        "<b>Non-Executing Analysis Guarantee:</b> All repository scanning, manifest parsing, and AST usage "
        "mapping were performed without executing repository code, importing setup.py, or running tests. "
        "Repository code and verification test suites remain unexecuted pending explicit human authorization."
    )
    elements.append(Paragraph(attestation_text, body_style))

    doc.build(elements, canvasmaker=NumberedCanvas)
    return buf.getvalue()


def save_capsule_pdf(capsule: DependencyExitCapsule, output_path: Union[str, Path]) -> Path:
    """Render capsule and write PDF to target file path."""
    dest = Path(output_path).resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)
    pdf_bytes = build_capsule_pdf_bytes(capsule)
    dest.write_bytes(pdf_bytes)
    return dest
